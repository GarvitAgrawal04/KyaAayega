// Generates a SYNTHETIC corpus so the pipeline, tests and demo page run before any real paper is parsed.
// It has a frequency signal built in on purpose; scores on it mean nothing. Replace with real, officially published papers.
import fs from "node:fs";
import path from "node:path";
const root = path.resolve("ledger/demo-univ/demo-os");
fs.mkdirSync(path.join(root, "papers"), { recursive: true });
function mulberry32(a) {
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const rnd = mulberry32(20260920);
const units = [
  ["u1", "Introduction", ["Types of operating systems", "System calls", "OS structure", "Booting"]],
  ["u2", "Processes", ["CPU scheduling algorithms", "Process states and PCB", "Threads", "Context switching"]],
  ["u3", "Synchronisation", ["Bankers algorithm", "Semaphores", "Critical section", "Deadlock detection"]],
  ["u4", "Memory", ["Page replacement", "Paging and segmentation", "Thrashing", "Virtual memory"]],
  ["u5", "Storage", ["Disk scheduling", "File allocation", "Directory structure", "RAID levels"]],
];
const slug = (s) => "t-" + s.toLowerCase().replace(/[^a-z0-9]+/g, "-");
const syllabus = {
  university: "demo-univ",
  subject: "demo-os",
  title: "Operating Systems (SYNTHETIC demo)",
  fixed_on: "2026-09-20",
  units: units.map(([id, name, ts]) => ({ id, name, topics: ts.map((t) => ({ id: slug(t), name: t, aliases: [] })) })),
};
fs.writeFileSync(path.join(root, "syllabus.json"), JSON.stringify(syllabus, null, 2) + "\n");
const topics = syllabus.units.flatMap((u) => u.topics.map((t) => t.id));
const weight = new Map(topics.map((t, i) => [t, [9, 3, 1, 1, 10, 5, 3, 1, 9, 7, 4, 2, 9, 6, 2, 3, 7, 5, 2, 1][i]]));
function pick(exclude) {
  const pool = topics.filter((t) => !exclude.has(t));
  const total = pool.reduce((a, t) => a + weight.get(t), 0);
  let r = rnd() * total;
  for (const t of pool) {
    r -= weight.get(t);
    if (r <= 0) return t;
  }
  return pool[pool.length - 1];
}
const name = new Map(syllabus.units.flatMap((u) => u.topics.map((t) => [t.id, t.name])));
for (const year of [2018, 2019, 2020, 2021, 2022, 2023, 2024]) {
  const sitting = `${year}-12`;
  const used = new Set();
  const questions = [];
  for (let i = 1; i <= 5; i++) {
    const t = pick(used);
    used.add(t);
    questions.push({
      id: `A-1${"abcde"[i - 1]}`,
      section: "A",
      number: `1${"abcde"[i - 1]}`,
      marks: 2,
      or_group: null,
      descriptor: `${name.get(t)} short note`,
      topic_ids: [t],
    });
  }
  const usedLong = new Set();
  for (let i = 1; i <= 6; i++) {
    const t = pick(usedLong);
    usedLong.add(t);
    const two = rnd() < 0.2;
    const t2 = two ? pick(new Set([...usedLong])) : null;
    questions.push({
      id: `B-${i + 1}`,
      section: "B",
      number: `${i + 1}`,
      marks: 10,
      or_group: null,
      descriptor: `${name.get(t)} long answer`,
      topic_ids: t2 ? [t, t2] : [t],
    });
  }
  for (let i = 1; i <= 2; i++) {
    const t = pick(usedLong);
    usedLong.add(t);
    questions.push({
      id: `C-8${"ab"[i - 1]}`,
      section: "C",
      number: `8${"ab"[i - 1]}`,
      marks: 10,
      or_group: "C-or",
      descriptor: `${name.get(t)} numerical`,
      topic_ids: [t],
    });
  }
  const paper = {
    id: `demo-univ/demo-os/${sitting}`,
    university: "demo-univ",
    subject: "demo-os",
    sitting,
    course_code: "DEMO-OS",
    max_marks: 60,
    source_url: "SYNTHETIC - generated by scripts/make-synthetic.mjs",
    synthetic: true,
    sections: [
      { id: "A", attempt: 5, of: 5 },
      { id: "B", attempt: 4, of: 6 },
      { id: "C", attempt: 1, of: 1 },
    ],
    questions,
  };
  fs.writeFileSync(path.join(root, "papers", `${sitting}.json`), JSON.stringify(paper, null, 2) + "\n");
}
console.log("synthetic corpus written to", root);
